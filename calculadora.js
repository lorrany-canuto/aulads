function somarnumeros(a,b){
    return a+b;
}

function subtracao(a,b){
    return a-b;
}

function multiplicar(a,b){
    return a*b;
}

module.exports= multiplicar

function dividir(a,b){
    return a/b;
module.exports= dividir
}

module.exports={
    somarnumeros:somarnumeros,
    subtracao:subtracao,
    multiplicar:multiplicar,
    dividir:dividir
}
